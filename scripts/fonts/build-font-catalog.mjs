#!/usr/bin/env node
// Builds packages/shared/src/font-catalog.ts from Google Fonts' public family
// metadata (https://fonts.google.com/metadata/fonts): the most used open
// families, with what a site needs to choose and load them. Run by hand when
// the catalog should be refreshed; the build and the tests never fetch it.
//
//   node scripts/fonts/build-font-catalog.mjs [metadata.json]
import { readFileSync, writeFileSync } from 'node:fs';

const LIMIT = 250;
const source = process.argv[2]
  ? JSON.parse(readFileSync(process.argv[2], 'utf8'))
  : await (await fetch('https://fonts.google.com/metadata/fonts')).json();
const CATEGORY = { 'Sans Serif': 'sans', Serif: 'serif', Display: 'display', Handwriting: 'handwriting', Monospace: 'mono' };

const families = source.familyMetadataList
  .filter((family) => family.isOpenSource && !family.isNoto && !family.isBrandFont && family.subsets.includes('latin') && CATEGORY[family.category])
  .sort((a, b) => a.popularity - b.popularity)
  .slice(0, LIMIT)
  .map((family) => {
    const styles = Object.keys(family.fonts);
    const weights = [...new Set(styles.map((style) => Number.parseInt(style, 10)))].sort((a, b) => a - b);
    const italic = [...new Set(styles.filter((style) => style.endsWith('i')).map((style) => Number.parseInt(style, 10)))].sort((a, b) => a - b);
    const wght = family.axes.find((axis) => axis.tag === 'wght');
    return {
      family: family.family,
      category: CATEGORY[family.category],
      weights,
      ...(italic.length ? { italic } : {}),
      ...(wght ? { variable: [wght.min, wght.max] } : {}),
      ...(family.subsets.includes('latin-ext') ? { latin_ext: true } : {}),
    };
  })
  .sort((a, b) => a.family.localeCompare(b.family));

const lines = families.map((family) => `  ${JSON.stringify(family)},`);
writeFileSync(new URL('../../packages/shared/src/font-catalog.ts', import.meta.url), `// Generated by scripts/fonts/build-font-catalog.mjs from Google Fonts' public
// metadata: the ${LIMIT} most used open-licence families (SIL OFL, Apache or UFL).
// Do not edit by hand; rerun the script to refresh it.

export interface CatalogFont {
  family: string;
  category: 'sans' | 'serif' | 'display' | 'handwriting' | 'mono';
  /** Weights the family has (100–900). */
  weights: number[];
  /** Weights that also have an italic. */
  italic?: number[];
  /** The weight axis range of a variable family. */
  variable?: [number, number];
  /** Has the extended Latin subset (Polish, Czech, Turkish and more). */
  latin_ext?: boolean;
}

export const FONT_CATALOG: readonly CatalogFont[] = [
${lines.join('\n')}
];
`);
console.log(`${families.length} families`);
